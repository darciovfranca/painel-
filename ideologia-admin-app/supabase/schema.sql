-- IDEOLOGIA MEMORIAL: banco, autenticação, permissões e desbloqueio seguro
create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text,
  avatar_url text,
  role text not null default 'user' check (role in ('admin','user')),
  created_at timestamptz not null default now()
);

-- O primeiro usuário cadastrado torna-se administrador. O lock evita dois primeiros admins simultâneos.
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public, auth as $$
declare new_role text;
begin
  perform pg_advisory_xact_lock(817263541);
  if not exists (select 1 from public.profiles where role = 'admin') then new_role := 'admin'; else new_role := 'user'; end if;
  insert into public.profiles(id, display_name, avatar_url, role)
  values (new.id, coalesce(new.raw_user_meta_data->>'full_name', new.raw_user_meta_data->>'name', new.email), new.raw_user_meta_data->>'avatar_url', new_role)
  on conflict (id) do nothing;
  return new;
end; $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute procedure public.handle_new_user();

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path=public as $$
  select exists(select 1 from public.profiles where id = auth.uid() and role='admin');
$$;

create table if not exists public.albums (
  id integer primary key,
  title text not null,
  subtitle text default '',
  cover_url text default '',
  sort_order integer not null default 0
);
create table if not exists public.chapters (
  id integer generated by default as identity primary key,
  album_id integer references public.albums(id) on delete cascade,
  title text not null,
  body text not null default '',
  sort_order integer not null default 0
);
create table if not exists public.stickers (
  id integer primary key check (id between 1 and 52),
  album_id integer not null references public.albums(id),
  name text not null,
  hint text not null default '',
  image_url text default '',
  rarity text default '',
  sort_order integer not null default 0
);
-- Respostas ficam em tabela separada, sem leitura pública.
create table if not exists public.sticker_secrets (
  sticker_id integer primary key references public.stickers(id) on delete cascade,
