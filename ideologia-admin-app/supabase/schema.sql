drop policy if exists "profile own or admin read" on public.profiles;
create policy "profile own or admin read" on public.profiles for select using (id=auth.uid() or public.is_admin());
drop policy if exists "admin update profiles" on public.profiles;
create policy "admin update profiles" on public.profiles for update using (public.is_admin()) with check (public.is_admin());

-- Conteúdo é público para leitura; somente admin pode alterar.
do $$ declare t text; begin
 foreach t in array array['albums','chapters','stickers','tracks','site_settings'] loop
  execute format('drop policy if exists "public read %1$s" on public.%1$I',t);
  execute format('create policy "public read %1$s" on public.%1$I for select using (true)',t);
  execute format('drop policy if exists "admin manage %1$s" on public.%1$I',t);
  execute format('create policy "admin manage %1$s" on public.%1$I for all using (public.is_admin()) with check (public.is_admin())',t);
 end loop;
end $$;
drop policy if exists "admin manage secrets" on public.sticker_secrets;
create policy "admin manage secrets" on public.sticker_secrets for all using (public.is_admin()) with check (public.is_admin());
drop policy if exists "users read own collection" on public.user_stickers;
create policy "users read own collection" on public.user_stickers for select using (user_id=auth.uid());

-- Verifica a senha no servidor; a resposta nunca precisa ser enviada ao navegador.
create or replace function public.unlock_sticker(p_sticker_id integer, p_answer text)
returns boolean language plpgsql security definer set search_path=public as $$
declare expected text;
begin
 if auth.uid() is null then raise exception 'Faça login para desbloquear figurinhas.'; end if;
 select answer into expected from public.sticker_secrets where sticker_id=p_sticker_id;
 if expected is null then return false; end if;
 if lower(regexp_replace(trim(coalesce(p_answer,'')), '\s+', ' ', 'g')) <> lower(regexp_replace(trim(expected), '\s+', ' ', 'g')) then return false; end if;
 insert into public.user_stickers(user_id,sticker_id) values(auth.uid(),p_sticker_id) on conflict do nothing;
 return true;
end; $$;
grant execute on function public.unlock_sticker(integer,text) to authenticated;

